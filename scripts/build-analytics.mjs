// Turns analytics/*.html into functions/_lib/pages.gen.js (Pages Functions can only import JS).
import { readFile, writeFile } from 'node:fs/promises';
const [app, login] = await Promise.all([readFile('analytics/app.html', 'utf8'), readFile('analytics/login.html', 'utf8')]);
await writeFile('functions/_lib/pages.gen.js', `// generated by scripts/build-analytics.mjs from analytics/*.html: do not edit by hand\nexport const APP = ${JSON.stringify(app)};\nexport const LOGIN = ${JSON.stringify(login)};\n`);
console.log('analytics pages generated');
